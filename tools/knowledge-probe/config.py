def build_grader_prompt(question: str, reference_answer: str,
                        grading_notes: str, answers: list) -> str:
    """Собирает пользовательскую часть промпта грейдера."""
    lines = [
        f"ВОПРОС:\n{question}\n",
        f"ЭТАЛОННЫЙ ОТВЕТ:\n{reference_answer}\n",
        f"ЗАМЕТКИ ДЛЯ ОЦЕНКИ (grading_notes):\n{grading_notes or '(нет)'}\n",
        f"ОТВЕТЫ МОДЕЛИ (всего {len(answers)}):",
    ]
    for i, ans in enumerate(answers):
        lines.append(f"\n--- Ответ [{i}] ---\n{ans}")
    lines.append(
        "\n\nОцени каждый ответ и выведи агрегат. Верни ТОЛЬКО JSON по заданной схеме."
    )
    return "\n".join(lines)


